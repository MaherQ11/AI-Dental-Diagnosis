from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Image, Table, TableStyle
from reportlab.lib.enums import TA_CENTER, TA_LEFT
from pathlib import Path
from django.conf import settings
import os
from datetime import datetime


def generate_pdf_report(patient, diagnosis_record) -> str:
    """
    Generate a PDF diagnostic report for a patient's dental scan.
    Returns the path to the saved PDF.
    """
    reports_dir = Path(settings.MEDIA_ROOT) / 'reports'
    reports_dir.mkdir(parents=True, exist_ok=True)

    filename = f"patient_{patient.id}_{Path(str(diagnosis_record.uploaded_image)).stem}_report.pdf"
    pdf_path = reports_dir / filename

    doc = SimpleDocTemplate(
        str(pdf_path),
        pagesize=A4,
        rightMargin=2*cm,
        leftMargin=2*cm,
        topMargin=2*cm,
        bottomMargin=2*cm,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        'Title', parent=styles['Title'],
        fontSize=20, textColor=colors.HexColor('#1a4a7a'),
        spaceAfter=0.3*cm, alignment=TA_CENTER,
    )
    heading_style = ParagraphStyle(
        'Heading', parent=styles['Heading2'],
        fontSize=13, textColor=colors.HexColor('#1a4a7a'),
        spaceBefore=0.4*cm, spaceAfter=0.2*cm,
    )
    body_style = ParagraphStyle(
        'Body', parent=styles['Normal'],
        fontSize=11, leading=16,
    )

    story = []

    # Header
    story.append(Paragraph("AI Dental Diagnosis Report", title_style))
    story.append(Paragraph("Powered by YOLOv8 — AIDentify System", ParagraphStyle(
        'sub', parent=styles['Normal'], fontSize=10,
        textColor=colors.grey, alignment=TA_CENTER, spaceAfter=0.5*cm
    )))

    # Divider
    story.append(Table([['']], colWidths=[17*cm],
        style=TableStyle([('LINEABOVE', (0,0), (-1,-1), 1.5, colors.HexColor('#1a4a7a'))])))
    story.append(Spacer(1, 0.3*cm))

    # Patient info
    story.append(Paragraph("Patient Information", heading_style))
    patient_data = [
        ['Name:', patient.user.get_full_name() or patient.user.username],
        ['Date:', datetime.now().strftime('%B %d, %Y')],
        ['Report ID:', f"#{diagnosis_record.id}"],
    ]
    t = Table(patient_data, colWidths=[4*cm, 13*cm])
    t.setStyle(TableStyle([
        ('FONTNAME', (0,0), (0,-1), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,-1), 11),
        ('TOPPADDING', (0,0), (-1,-1), 4),
        ('BOTTOMPADDING', (0,0), (-1,-1), 4),
    ]))
    story.append(t)
    story.append(Spacer(1, 0.4*cm))

    # Scan image
    if diagnosis_record.processed_image and os.path.exists(
        os.path.join(settings.MEDIA_ROOT, str(diagnosis_record.processed_image))
    ):
        story.append(Paragraph("Analyzed Dental Scan", heading_style))
        img_path = os.path.join(settings.MEDIA_ROOT, str(diagnosis_record.processed_image))
        img = Image(img_path, width=10*cm, height=7.5*cm, kind='proportional')
        story.append(img)
        story.append(Spacer(1, 0.4*cm))

    # Detection results
    story.append(Paragraph("Detection Results", heading_style))
    detections = diagnosis_record.detection_json if diagnosis_record.detection_json else []

    if not detections:
        story.append(Paragraph("No dental conditions were detected in this scan.", body_style))
    else:
        for i, det in enumerate(detections, 1):
            condition = det.get('class_name', 'Unknown')
            confidence = det.get('confidence', 0)
            description = det.get('description', '')

            color = colors.HexColor('#d32f2f') if confidence > 70 else colors.HexColor('#f57c00')
            conf_style = ParagraphStyle(
                f'conf_{i}', parent=styles['Normal'],
                fontSize=11, textColor=color,
            )
            story.append(Paragraph(
                f"<b>{i}. {condition}</b> — Confidence: {confidence}%", conf_style
            ))
            if description:
                story.append(Paragraph(f"   {description}", ParagraphStyle(
                    f'desc_{i}', parent=styles['Normal'],
                    fontSize=10, textColor=colors.grey, leftIndent=15, spaceAfter=6
                )))

    story.append(Spacer(1, 0.4*cm))

    # Disclaimer
    story.append(Table([['']], colWidths=[17*cm],
        style=TableStyle([('LINEABOVE', (0,0), (-1,-1), 0.5, colors.grey)])))
    story.append(Spacer(1, 0.2*cm))
    story.append(Paragraph(
        "⚠ This report is generated by an AI system and is intended for preliminary screening "
        "purposes only. Please consult a licensed dentist for professional diagnosis and treatment.",
        ParagraphStyle('disclaimer', parent=styles['Normal'],
            fontSize=9, textColor=colors.grey, alignment=TA_CENTER)
    ))

    doc.build(story)
    return str(pdf_path)
